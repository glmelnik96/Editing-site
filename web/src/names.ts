/**
 * Подпись куска на шкале: имя записи и длительность.
 *
 * Раньше на блоке стоял внутренний номер (`c3_945zdp`): человек ищет «интервью.mp4», а видит код.
 * Номер остаётся в подсказке блока — его ищет агент. Без записи в списке — номер, чтобы подпись
 * не пустела.
 */
export function pieceLabel(name: string | null | undefined, id: string, length: string): string {
  return `${name || id} · ${length}`
}
