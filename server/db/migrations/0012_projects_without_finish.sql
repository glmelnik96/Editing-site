-- Состояние «завершён» убрано целиком: завершённый проект нельзя было ни открыть, ни собрать,
-- ни восстановить — его файлы уже удалены. Это была худшая версия удаления, и держать ради неё
-- отдельное состояние незачем. Осталось два: проект есть или его нет.
--
-- Вместе с состоянием уходит единственный способ освободить исходники, не трогая проект: теперь
-- запись живёт, пока жив проект, а освобождает её удаление проекта. Так честнее — забрать у
-- проекта файлы и оставить имя значило оставить пустышку.
--
-- Уже завершённые проекты удаляем: их файлов на диске нет, открыть или собрать их невозможно,
-- и после снятия состояния они выглядели бы обычными, но сломанными. Каталоги на диске подберёт
-- janitor правилом о сиротах.
DELETE FROM projects WHERE status = 'finished';

-- SQLite умеет DROP COLUMN с 3.35; на ВМ 3.45. Пересборка таблицы здесь опаснее: на projects
-- ссылаются project_versions и renders, и DROP TABLE каскадом снёс бы их строки.
ALTER TABLE projects DROP COLUMN status;
ALTER TABLE projects DROP COLUMN finished_at;
